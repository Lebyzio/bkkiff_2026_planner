// Regenerates src/lib/pdfFont.generated.ts from the vendored Thai font, so
// the PDF export can embed it without any runtime fetch.
// Run with: npm run generate:pdf-font
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.join(__dirname, "..", "assets", "fonts", "NotoSansThai-Regular.ttf");
const OUTPUT = path.join(__dirname, "..", "src", "lib", "pdfFont.generated.ts");

const base64 = readFileSync(SOURCE).toString("base64");

const contents = `// Generated by scripts/generate-pdf-font.mjs from assets/fonts/NotoSansThai-Regular.ttf.
// Do not edit by hand — see assets/fonts/NOTICE.md for provenance and regeneration.
export const NOTO_SANS_THAI_REGULAR_BASE64 = ${JSON.stringify(base64)};
`;

writeFileSync(OUTPUT, contents);
console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} (${Math.round(base64.length / 1024)} KB base64)`);
